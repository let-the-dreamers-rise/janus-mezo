/// Copies everything the web app shares with the keeper into web/, so the web app builds on
/// its own (Vercel only sees web/) while the keeper stays the single source of truth:
///   - Janus ABIs from the Foundry build (keeper and web)
///   - Mezo ABIs and addresses (web)
///   - the keeper's pure decision code: epochs, round planner, shard and boost signals and
///     gas-fitted batching, so the web app's "Run next step" decides exactly as the keeper
///   - the matsnet deployment record, once contracts/deployments/31611.json exists (web)
/// Usage: pnpm sync   (run `forge build` in ../contracts first)
import { copyFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const at = (path: string) => resolve(root, path);

const CONTRACTS = [
  { exportName: "janusVaultAbi", artifact: "JanusVault.sol/JanusVault.json" },
  { exportName: "boostMarketAbi", artifact: "BoostMarket.sol/BoostMarket.json" },
] as const;

const SHARED_LIB = ["epochs", "planner", "shards", "boosts", "batch", "gas"] as const;

const COPIES = [
  { from: "keeper/src/abi/mezo.ts", to: "web/src/lib/abi/mezo.ts" },
  { from: "keeper/src/config/addresses.ts", to: "web/src/config/mezo-addresses.ts" },
  ...SHARED_LIB.map((name) => ({ from: `keeper/src/lib/${name}.ts`, to: `web/src/lib/protocol/keeper/${name}.ts` })),
] as const;

/// The keeper runs as Node ESM and imports siblings as "./x.js"; the web bundler wants "./x".
const forBundler = (source: string) => source.replace(/from "(\.\.?\/[^"]+)\.js"/g, 'from "$1"');

const DEPLOYMENT = { from: "contracts/deployments/31611.json", to: "web/src/config/deployment.json" };

function readAbi(artifact: string): unknown[] {
  const path = at(`contracts/out/${artifact}`);
  if (!existsSync(path)) throw new Error(`Missing ${path}. Run forge build in contracts/ first.`);
  const parsed: unknown = JSON.parse(readFileSync(path, "utf8"));
  const abi = typeof parsed === "object" && parsed !== null ? (parsed as { abi?: unknown }).abi : undefined;
  if (!Array.isArray(abi)) throw new Error(`No abi array in ${path}`);
  return abi;
}

function write(target: string, contents: string): void {
  mkdirSync(dirname(at(target)), { recursive: true });
  writeFileSync(at(target), contents);
  console.log(`wrote ${target}`);
}

const abiBody = CONTRACTS.map(
  ({ exportName, artifact }) =>
    `export const ${exportName} = ${JSON.stringify(readAbi(artifact), null, 2)} as const;\n`,
).join("\n");
const abiFile = `// Generated by keeper/scripts/sync-artifacts.ts from the Foundry build. Do not edit by hand.\n\n${abiBody}`;
write("keeper/src/abi/janus.ts", abiFile);

const web = existsSync(at("web/package.json"));
if (web) {
  write("web/src/lib/abi/janus.ts", abiFile);
  for (const { from, to } of COPIES) {
    const header = `// Generated from ${from} by keeper/scripts/sync-artifacts.ts. Do not edit by hand.\n`;
    write(to, header + forBundler(readFileSync(at(from), "utf8")));
  }
  if (existsSync(at(DEPLOYMENT.from))) {
    mkdirSync(dirname(at(DEPLOYMENT.to)), { recursive: true });
    copyFileSync(at(DEPLOYMENT.from), at(DEPLOYMENT.to));
    console.log(`wrote ${DEPLOYMENT.to}`);
  } else {
    console.log(`no ${DEPLOYMENT.from} yet; web keeps its current deployment record`);
  }
}
